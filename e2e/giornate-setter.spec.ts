/**
 * What the seed setter's own clients and calls add up to in the period (check only: the page reads SQL).
 * Money is only the new clients he brought (29/09/2026): the first instalment of
 * each new sale, on the day of the sale, and the contracts of the new sales.
 */
async function attesiDelSetter() {
  const db = dbLocale()
  const [incassi, vendite, call, clienti, report] = await Promise.all([
    db
      .from('payments')
      .select('importo_incassato, sales!inner(setter_id, tipo, data_vendita)')
      .eq('stato', 'incassata')
      .eq('numero_rata', 1)
      .eq('sales.setter_id', ID_SETTER)
      .eq('sales.tipo', 'nuovo')
      .gte('sales.data_vendita', DA)
      .lte('sales.data_vendita', A),
    db
      .from('sales')
      .select('valore_contratto')
      .eq('setter_id', ID_SETTER)
      .eq('tipo', 'nuovo')
      .gte('data_vendita', DA)
      .lte('data_vendita', A),
    db
      .from('calls')
      .select('id', { count: 'exact', head: true })
      .eq('setter_id', ID_SETTER)
      .eq('stato', 'svolta')
      .gte('programmata_il', `${DA}T00:00:00+01:00`)
      .lt('programmata_il', '2027-01-01T00:00:00+01:00'),
    db.from('clients').select('nome, cognome').not('setter_id', 'is', null),
    db
      .from('setter_daily_reports')
      .select('dm_outbound, dm_inbound, follow_up, strategy_prenotate')
      .eq('setter_id', ID_SETTER)
      .gte('data', DA)
      .lte('data', A),
  ])
  for (const r of [incassi, vendite, call, clienti, report]) if (r.error) throw r.error
  return {
    // DM totali = outbound + inbound + follow up (Dany, 28/09/2026)
    dmTotali: (report.data ?? []).reduce((s, r) => s + r.dm_outbound + r.dm_inbound + r.follow_up, 0),
    strategy: (report.data ?? []).reduce((s, r) => s + r.strategy_prenotate, 0),
    cash: (incassi.data ?? []).reduce((s, p) => s + centesimi(p.importo_incassato), 0) / 100,
    revenue: (vendite.data ?? []).reduce((s, v) => s + centesimi(v.valore_contratto), 0) / 100,
    call: call.count ?? 0,
    nomiClienti: (clienti.data ?? []).map((c) => [c.nome, c.cognome].filter(Boolean).join(' ')),
  }
}

/** The table's header texts and their titles (the full names), in order. */
async function intestazioni(tabella: Locator) {
  const celle = tabella.locator('thead th')
  return {
    testi: (await celle.allInnerTexts()).map((t) => t.replace(/\s+/g, ' ').trim()),
    titoli: await celle.evaluateAll((th) => th.map((c) => c.getAttribute('title'))),
  }
}

/** The body rows of a table, as the texts of their value cells. */
async function righe(tabella: Locator) {
  return tabella.locator('tbody tr').evaluateAll((rr) => rr.map((r) => [...r.querySelectorAll('td')].map((c) => c.textContent ?? '')))
}

test('setter a 1440px: giorno per giorno in due tabelle, una per fonte, senza scroll orizzontale', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const attesi = await attesiDelSetter()
  await accedi(page, 'setter')
  await page.goto(URL)

  const sezione = page.getByTestId('mie-giornate')
  await expect(sezione.getByRole('heading', { name: 'Giorno per giorno' })).toBeVisible()
  const report = sezione.getByRole('table', { name: 'Il tuo report' })
  const call = sezione.getByRole('table', { name: 'Le call col tuo nome' })
  await expect(report).toBeVisible()
  await expect(call).toBeVisible()
  // the two sources never share a table: each says where its numbers come from
  await expect(sezione.getByTestId('tabella-report')).toContainText('I numeri che scrivi ogni giorno in «Oggi»')
  await expect(sezione.getByTestId('tabella-call')).toContainText('per giorno di prenotazione')

  // the report: the DM split and their total; the seed's past days hold strategy
  // calls (history), so the period shows them in a column of their own
  expect(attesi.strategy).toBeGreaterThan(0)
  const r = await intestazioni(report)
  expect(r.testi).toEqual([
    'Giorno',
    'DM out',
    'DM in',
    'Follow up',
    'DM totali',
    'Conv.',
    'Call proposte',
    'Disc. prenotate',
    'Strategy (storico)',
  ])
  expect(r.titoli.slice(1)).toEqual([
    'DM outbound',
    'DM inbound',
    'Follow up',
    'DM totali',
    'Conversazioni',
    'Call proposte',
    'Discovery prenotate',
    'Strategy (storico)',
  ])
  // the calls: bookings by source, then the closer's results; shared names say "closer"
  const c = await intestazioni(call)
  expect(c.testi).toEqual([
    'Giorno',
    'Da inbound',
    'Da outbound',
    'Svolte',
    'Qualif. closer',
    'No show',
    'Follow up closer',
    'Cancellate',
    'Chiuse',
    'Cash',
    'Revenue',
  ])
  expect(c.titoli.slice(1, 7)).toEqual([
    'Prenotate da DM inbound',
    'Prenotate da DM outbound',
    'Call svolte',
    'Qualificate (closer)',
    'No show',
    'Follow up (closer)',
  ])
  // a short header never repeats within a table
  for (const { testi } of [r, c]) expect(new Set(testi).size).toBe(testi.length)

  // both fit the page at 1440: no scrolling inside, none of the page
  const scorrono = await sezione
    .locator('[role="region"]')
    .evaluateAll((regioni) => regioni.map((el) => el.scrollWidth > el.clientWidth))
  expect(scorrono).toEqual([false, false])
  expect(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)).toBe(false)

  // total rows from SQL: the report's DM, the closer's calls, cash and revenue only of his own calls and clients
  const totaleReport = report.locator('tfoot tr')
  await expect(totaleReport.getByRole('rowheader')).toHaveText('Totale')
  await expect(totaleReport.getByRole('cell')).toHaveCount(8)
  await expect(totaleReport.getByRole('cell').nth(3)).toHaveText(formatNumero(attesi.dmTotali))
  await expect(totaleReport.getByRole('cell').nth(7)).toHaveText(formatNumero(attesi.strategy))
  const totaleCall = call.locator('tfoot tr')
  await expect(totaleCall.getByRole('rowheader')).toHaveText('Totale')
  const celleCall = totaleCall.getByRole('cell')
  await expect(celleCall).toHaveCount(10)
  await expect(celleCall.nth(2)).toHaveText(formatNumero(attesi.call))
  await expect(celleCall.nth(8)).toHaveText(formatEuro(attesi.cash))
  await expect(celleCall.nth(9)).toHaveText(formatEuro(attesi.revenue))

  // each table lists only the days where its source has a number
  const giorniReport = await righe(report)
  const giorniCall = await righe(call)
  expect(giorniReport.length).toBeGreaterThan(0)
  expect(giorniCall.length).toBeGreaterThan(0)
  for (const celle of [...giorniReport, ...giorniCall]) expect(celle.some((t) => leggiNumero(t) !== 0)).toBe(true)
  // every day and the total: DM totali (from SQL) is outbound + inbound + follow up
  const celleTotale = await totaleReport.evaluate((riga) => [...riga.querySelectorAll('td')].map((td) => td.textContent ?? ''))
  for (const celle of [...giorniReport, celleTotale]) {
    expect(leggiNumero(celle[3])).toBe(leggiNumero(celle[0]) + leggiNumero(celle[1]) + leggiNumero(celle[2]))
  }

  // the other setter's client: not his money, not his call, never a name
  const testo = (await sezione.innerText()).replace(/\s+/g, ' ')
  expect(testo).not.toContain(formatEuro(IMPORTO_ALTRUI))
  expect(testo).not.toContain(nomeAltrui)
  for (const nome of attesi.nomiClienti) expect(testo).not.toContain(nome)

  // the legend says cash and revenue are of his clients, not of the closer's sales
  const legenda = page.getByTestId('legenda')
  await legenda.getByText('Cosa significa ogni numero').click()
  await expect(legenda).toContainText(LEGENDA_SETTER.cash_miei_clienti.spiegazione)
  await expect(legenda).toContainText(LEGENDA_SETTER.revenue_miei_clienti.spiegazione)
  await expect(legenda).not.toContainText(LEGENDA_CLOSER.cash.spiegazione)
  await expect(legenda.getByText('In agenda nel periodo', { exact: true })).toBeVisible()
  await expect(legenda.getByText('Strategy (storico)', { exact: true })).toBeVisible()
})

test('setter a 390px: il totale aperto in cima, poi una riga chiusa per giorno, nessuno scroll orizzontale', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await accedi(page, 'setter')
  await page.goto(URL)

  const sezione = page.getByTestId('mie-giornate')
  // the two desktop tables are in the page, hidden on the phone
  await expect(sezione.locator('table')).toHaveCount(2)
  for (const tabella of await sezione.locator('table').all()) await expect(tabella).toBeHidden()

  // the total first, open, with every number of both sources
  const totale = sezione.locator('details[data-testid="giornata-totale"]')
  await expect(totale).toHaveAttribute('open', '')
  await expect(totale.locator('summary')).toHaveText('Totale del periodo')
  await expect(totale).toContainText('Il tuo report')
  await expect(totale).toContainText('Le call col tuo nome')
  await expect(totale).toContainText('per giorno di prenotazione')
  for (const etichetta of [
    'DM outbound',
    'DM inbound',
    'Follow up',
    'DM totali',
    'Strategy (storico)',
    'Prenotate da DM inbound',
    'Prenotate da DM outbound',
  ]) {
    await expect(totale).toContainText(etichetta)
  }
  // never two identical labels: the closer's say "(closer)"
  const etichette = await totale.locator('dt').allInnerTexts()
  expect(new Set(etichette).size).toBe(etichette.length)
  expect(etichette).toEqual(expect.arrayContaining(['Qualificate (closer)', 'Follow up', 'Follow up (closer)']))

  // then the days, closed: one line with the day and five numbers, each named for screen readers
  const giorni = sezione.getByRole('list', { name: 'Giorni del periodo' }).getByRole('listitem')
  await expect(giorni.first()).toBeVisible()
  const primo = giorni.first()
  const dettagli = primo.locator('details')
  await expect(dettagli).not.toHaveAttribute('open')
  const riga = primo.locator('summary')
  await expect(riga).toContainText(/\d{2}\/\d{2}\/\d{4}/)
  for (const nome of ['DM totali', 'Discovery prenotate', 'Call svolte', 'Chiuse', 'Cash']) await expect(riga).toContainText(`${nome}:`)
  const altezza = (await riga.boundingBox())?.height ?? 0
  expect(altezza).toBeGreaterThanOrEqual(44)
  expect(altezza).toBeLessThan(60)
  await expect(primo.getByText('Il tuo report')).toBeHidden()

  // a tap opens it: the two sources, the numbers that are zero left out
  await riga.click()
  await expect(dettagli).toHaveAttribute('open', '')
  await expect(primo.getByText('Il tuo report')).toBeVisible()
  await expect(primo.getByText('Le call col tuo nome')).toBeVisible()
  const valori = await primo.locator('dd').allInnerTexts()
  expect(valori.length).toBeGreaterThan(0)
  for (const v of valori) expect(leggiNumero(v)).not.toBe(0)
  // amounts on the phone keep their two decimals, like every list
  await expect(riga).toContainText(/\d,\d{2}\s€/)
  await expect(totale).toContainText(/\d,\d{2}\s€/)

  const scorre = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(scorre).toBe(false)
})

test('setter: le strategy dello storico compaiono solo in un periodo che ne ha', async ({ page }) => {
  // a day far from every period the other tests look at, only for this setter
  const giorno = '2020-03-10'
  const periodo = '/my-numbers?da=2020-03-01&a=2020-03-31'
  const db = dbLocale()
  await db.from('setter_daily_reports').delete().eq('setter_id', ID_SETTER).eq('data', giorno)
  const { error } = await db
    .from('setter_daily_reports')
    .insert({ setter_id: ID_SETTER, data: giorno, dm_outbound: 9, discovery_prenotate: 1, created_by: ID_SETTER })
  if (error) throw error

  try {
    await page.setViewportSize({ width: 1440, height: 900 })
    await accedi(page, 'setter')
    await page.goto(periodo)
    const report = page.getByRole('table', { name: 'Il tuo report' })
    await expect(report).toBeVisible()
    await expect(report.locator('thead')).not.toContainText(/strategy/i)
    await expect(page.getByTestId('nota-call_prenotate')).toHaveCount(0)
    await expect(page.getByTestId('miei-numeri-setting')).not.toContainText(/strategy/i)

    await db.from('setter_daily_reports').update({ strategy_prenotate: 2 }).eq('setter_id', ID_SETTER).eq('data', giorno)
    await page.reload()
    await expect(report.locator('thead')).toContainText('Strategy (storico)')
    await expect(report.locator('tfoot td').nth(7)).toHaveText('2')
    // "Call prenotate" (discovery + strategy, from SQL) says how many are history
    await expect(page.getByTestId('numero-call_prenotate')).toHaveText('3')
    await expect(page.getByTestId('nota-call_prenotate')).toHaveText('di cui 2 strategy dallo storico')
  } finally {
    await db.from('setter_daily_reports').delete().eq('setter_id', ID_SETTER).eq('data', giorno)
  }
})

