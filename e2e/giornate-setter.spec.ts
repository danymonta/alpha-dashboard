// A client someone else brought (the admin as setter): his money and his call
// must never reach the seed setter's day by day.
const GIORNO_ALTRUI = '2026-02-17'
const IMPORTO_ALTRUI = 4321.99

/** Cents, so sums of amounts stay exact. */
function centesimi(v: number | string | null): number {
  return Math.round(Number(v ?? 0) * 100)
}

/** "5.569" or "4.321,99 €" back to a number, to read the table. */
function leggiNumero(testo: string): number {
  const pulito = testo.replace(/[^\d,-]/g, '').replace(',', '.')
  return pulito === '' ? 0 : Number(pulito)
}

