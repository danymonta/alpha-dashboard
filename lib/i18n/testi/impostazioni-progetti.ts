function contaIt(n: number, uno: string, piu: string): string {
  return n === 1 ? `1 ${uno}` : `${n} ${piu}`
}
function contaEn(n: number, uno: string, piu: string): string {
  return n === 1 ? `1 ${uno}` : `${n} ${piu}`
}

