const CAMPO_CAMBIATO = /^Il campo «(.+)» è cambiato da un’altra parte: ora vedi quello salvato\. Rifai la modifica, se serve\.$/
const AL_MASSIMO = /^(Audio: )?[Aa]l massimo (\d+) caratteri\.$/

/** An error of a content's action in the page's language: the Italian of always, or its English when known. */
export function traduciErroreContenuto(testo: string, lingua: Lingua): string {
  if (lingua === 'it') return testo
  const noto = ERRORI_CONTENUTO_EN[testo]
  if (noto) return noto
  const cambiato = CAMPO_CAMBIATO.exec(testo)
  if (cambiato) return `The field «${cambiato[1] === CAMPO_MODELLO ? 'Template' : cambiato[1]}» changed elsewhere: now you see the saved one. Make the change again, if needed.`
  const massimo = AL_MASSIMO.exec(testo)
  if (massimo) return `${massimo[1] ? 'Audio: at' : 'At'} most ${massimo[2]} characters.`
  return testo
}
