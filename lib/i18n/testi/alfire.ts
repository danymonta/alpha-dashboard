/** The red button of a destructive card (azioneDistruttiva, lib/alfire/riassunto.ts), in the page's language. */
const DISTRUTTIVE_EN: Record<string, string> = {
  Elimina: 'Delete',
  Interrompi: 'Stop',
  Togli: 'Remove',
}
export function bottoneDistruttivo(etichetta: string, lingua: Lingua): string {
  return lingua === 'it' ? etichetta : (DISTRUTTIVE_EN[etichetta] ?? etichetta)
}
