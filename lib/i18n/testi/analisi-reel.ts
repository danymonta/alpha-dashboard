/** «0,30 $» or «$0.30»: an estimate of the cost, in the page's language. */
export function usdIn(n: number, lingua: Lingua): string {
  const testo = n.toLocaleString(lingua === 'en' ? 'en-IE' : 'it-IT', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
  return lingua === 'en' ? `$${testo}` : `${testo} $`
}

