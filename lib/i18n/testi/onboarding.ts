/** A reason of the log in the page's language: the three automatic ones translate, the admin's own stay as written. */
export function motivoInLingua(motivo: string, lingua: Lingua): string {
  const chiave = (Object.keys(MOTIVI_AUTOMATICI) as (keyof typeof MOTIVI_AUTOMATICI)[]).find(
    (k) => MOTIVI_AUTOMATICI[k] === motivo,
  )
  return chiave ? ONBOARDING[lingua].registro.motivi[chiave] : motivo
}

/** The title of a step in the page's language: the dictionary's by key, else the database's own. */
export function titoloPasso(chiave: string | null | undefined, titoloSalvato: string | null | undefined, lingua: Lingua): string {
  const tradotto = chiave ? ONBOARDING[lingua].passi.titoli[chiave] : undefined
  return tradotto ?? titoloSalvato ?? chiave ?? ''
}

